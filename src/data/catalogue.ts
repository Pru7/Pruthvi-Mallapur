export const HOTELS_BY_ID = new Map<string, { hotel: Destination['hotels'][0]; destination: Destination }>();
export const ACTIVITIES_BY_ID = new Map<string, { activity: Destination['activities'][0]; destination: Destination }>();

for (const dest of TRAVEL_CATALOGUE) {
  DESTINATIONS_BY_ID.set(dest.id, dest);
  for (const htl of dest.hotels) {
    HOTELS_BY_ID.set(htl.id, { hotel: htl, destination: dest });
  }
  for (const act of dest.activities) {
    ACTIVITIES_BY_ID.set(act.id, { activity: act, destination: dest });
  }
}
